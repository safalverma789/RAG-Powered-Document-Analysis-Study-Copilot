from typing import List, Optional, Literal
from pydantic import BaseModel, Field


# ------------------------------------------------------------------------------
# Health Check
# ------------------------------------------------------------------------------
class HealthResponse(BaseModel):
    status: str = Field(default="ok", description="Server health status")


# ------------------------------------------------------------------------------
# Document Management
# ------------------------------------------------------------------------------
class UploadResponse(BaseModel):
    doc_id: str = Field(..., description="Unique document identifier")
    filename: str = Field(..., description="Original filename")
    chunk_count: int = Field(..., description="Number of text chunks created and stored")
    total_pages: int = Field(..., description="Total pages extracted from the document")
    message: str = Field(..., description="Status message")


class DocumentInfo(BaseModel):
    doc_id: str = Field(..., description="Unique document identifier")
    filename: str = Field(..., description="Original filename")
    chunk_count: int = Field(..., description="Total stored chunks for this document")
    total_pages: int = Field(..., description="Number of pages in the original document")
    uploaded_at: str = Field(..., description="ISO timestamp of upload")


class DocumentListResponse(BaseModel):
    documents: List[DocumentInfo] = Field(default_factory=list, description="List of all uploaded documents")
    total: int = Field(..., description="Total document count")


class DeleteResponse(BaseModel):
    message: str = Field(..., description="Confirmation message")
    doc_id: str = Field(..., description="Identifier of the deleted document")


# ------------------------------------------------------------------------------
# RAG Ask / Q&A
# ------------------------------------------------------------------------------
class AskRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Question to answer based on documents")
    doc_id: Optional[str] = Field(
        default=None,
        description="Optional doc_id to restrict answer search to a single document"
    )


class SourceChunk(BaseModel):
    filename: str = Field(..., description="Source document filename")
    page: int = Field(..., description="Source page number (1-indexed)")
    snippet: str = Field(..., description="Excerpt snippet of the chunk context")


class AskResponse(BaseModel):
    answer: str = Field(..., description="Answer generated by Gemini strictly from context")
    sources: List[SourceChunk] = Field(default_factory=list, description="Top retrieved chunk sources")


# ------------------------------------------------------------------------------
# Summarization
# ------------------------------------------------------------------------------
class SummarizeRequest(BaseModel):
    doc_id: str = Field(..., min_length=1, description="Document ID to summarize")
    style: Literal["short", "detailed"] = Field(
        default="short",
        description="Summary style: 'short' for high-level brief, 'detailed' for deep analysis"
    )


class SummarizeResponse(BaseModel):
    doc_id: str = Field(..., description="Document identifier")
    summary: str = Field(..., description="Map-reduce generated summary")
    style: str = Field(..., description="Style used for summarization")


# ------------------------------------------------------------------------------
# Key Points
# ------------------------------------------------------------------------------
class KeypointsRequest(BaseModel):
    doc_id: str = Field(..., min_length=1, description="Document ID to extract key points from")


class KeypointsResponse(BaseModel):
    doc_id: str = Field(..., description="Document identifier")
    key_points: List[str] = Field(default_factory=list, description="Extracted bullet points")


# ------------------------------------------------------------------------------
# Quiz Generation
# ------------------------------------------------------------------------------
class QuizRequest(BaseModel):
    doc_id: str = Field(..., min_length=1, description="Document ID to generate quiz for")
    num_questions: int = Field(default=5, ge=1, le=20, description="Number of questions (1-20)")
    difficulty: Literal["easy", "medium", "hard"] = Field(
        default="medium",
        description="Difficulty level of the quiz questions"
    )


class QuizQuestion(BaseModel):
    question: str = Field(..., description="The multiple choice question")
    options: List[str] = Field(..., description="4 answer options [A, B, C, D]")
    correct_answer: str = Field(..., description="Identifier or text of correct answer (e.g. 'A')")
    explanation: str = Field(..., description="Explanation why the answer is correct based on the text")


class QuizResponse(BaseModel):
    doc_id: str = Field(..., description="Document identifier")
    questions: List[QuizQuestion] = Field(..., description="List of generated quiz questions")


# ------------------------------------------------------------------------------
# Tutor Explanation
# ------------------------------------------------------------------------------
class ExplainRequest(BaseModel):
    doc_id: str = Field(..., min_length=1, description="Document ID containing the topic")
    topic: str = Field(..., min_length=1, description="Topic or concept to explain")


class ExplainResponse(BaseModel):
    doc_id: str = Field(..., description="Document identifier")
    topic: str = Field(..., description="Topic requested")
    explanation: str = Field(..., description="Tutor-style explanation based only on document")


# ------------------------------------------------------------------------------
# Error Schema
# ------------------------------------------------------------------------------
class ErrorResponse(BaseModel):
    detail: str = Field(..., description="Clear explanation of the error")
